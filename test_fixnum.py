# -*- coding: utf-8 -*-
"""fix_number / parse_cell 单元测试

2026-10-31 更新：审计发现的 5 个「静默算错数」缺陷各补一条（甚至多条）用例 ——
  ① 负整数丢符号（-5 写成 5）
  ② 点分日期被当数字毁掉（2024.01.23 → 202401.23）
  ③ 前导零丢失（0123 单号变 123）
  ④ 千分位两支判据不一致（7.500 → 7.5 而 7,500 → 7500）
  ⑤ 8 位日期被当整数（20240123 → 20,240,123）
"""
import sys
sys.stdout.reconfigure(encoding="utf-8")
import core

CASES = [
    # (输入, 期望值, 说明)
    ("2.903.00", 2903.0, "千分位点被认成小数点"),
    ("2,903.00", 2903.0, "标准千分位"),
    ("3,015.64", 3015.64, "标准千分位"),
    ("4. 69", 4.69, "小数点后误插空格"),
    ("2 . 9 0 3 . 0 0", 2903.0, "数字间多处空格"),
    ("4, 69", 4.69, "逗号后误插空格"),
    ("20240123", 20240123, "8 位日期在 fix_number 层保持 int（归一由 parse_cell 做）"),
    ("1.00", 1.0, "普通两位小数"),
    ("48,175.58", 48175.58, "大额标准写法"),
    ("2.925.67", 2925.67, "千分位点被认成小数点"),
    ("\u00a5123.45", 123.45, "带货币符号"),
    ("1,234,567.89", 1234567.89, "多级千分位"),
    ("2,903", 2903, "纯千分位整数"),
    ("3.14159", 3.14159, "多位小数"),
    ("4.6", 4.6, "一位小数"),
    # ---- 千分位判据统一后：点号与逗号必须给出同一个数 ----
    ("7.500", 7500, "点号千分位（旧实现算成 7.5，差 1000 倍）"),
    ("7,500", 7500, "逗号千分位"),
    ("12.345", 12345, "点号千分位（旧实现保持 12.345）"),
    ("12,345", 12345, "逗号千分位"),
    ("1.234", 1234, "点号千分位（旧实现保持 1.234）"),
    ("2.903", 2903, "点号千分位（旧实现保持 2.903）"),
    ("123.456", 123456, "整数部分符合分组规律 -> 修正"),
    ("1234.567", 1234.567, "整数部分 4 位不符合分组规律 -> 保持原样"),
    ("0.500", 0.5, "整数部分为 0 -> 是小数，不是千分位"),
    # ---- 负数：整数分支曾经漏掉符号 ----
    ("-5", -5, "负整数（旧实现输出 5）"),
    ("-1200", -1200, "负整数（旧实现输出 1200）"),
    ("-5.00", -5.0, "负小数"),
    ("+88", 88, "显式正号"),
    # ---- 点分日期不得参与数值清洗 ----
    ("2024.01.23", "2024.01.23", "点分日期（旧实现压成 202401.23）"),
    ("2024.1.23", "2024.1.23", "点分日期（单位数月日）"),
    ("100", 100, "纯整数"),
    # 以下应保持字符串
    ("", "", "空串"),
    ("-", "-", "单符号"),
    ("abc", "abc", "非数字"),
    ("2024年1月", "2024年1月", "中文混杂不猜测"),
]

fails = 0
for src, exp, note in CASES:
    got, raw = core.fix_number(src)
    ok = (got == exp) and (type(got) is type(exp))
    if not ok:
        fails += 1
        print(f"[FAIL] {src!r} -> {got!r} ({type(got).__name__})  期望 {exp!r}  | {note}")
    else:
        print(f"[ ok ] {src!r} -> {got!r}  | {note}")

# parse_cell：真正断言，不只是打印
print("\n-- parse_cell --")
PARSE_CASES = [
    # (输入, 期望值, 期望类型, 说明)
    ("20240123", "2024/01/23", "date", "8 位日期归一（旧实现输出 20240123 数值）"),
    ("2024-01-23", "2024/01/23", "date", "横杠日期归一"),
    ("2024.01.23", "2024/01/23", "date", "点分日期归一（旧实现输出 202401.23）"),
    ("2.903.00", 2903.0, "num", "千分位修正"),
    ("7.500", 7500, "num", "点号千分位"),
    ("-5", -5, "num", "负整数带符号"),
    ("0123", "0123", "text", "前导零单号按文本保留（旧实现变 123）"),
    ("0012345", "0012345", "text", "前导零单号按文本保留"),
    ("0.500", 0.5, "num", "前导 0 的小数不受影响"),
    ("代理付款", "代理付款", "text", "普通文本"),
    ("", "", "", "空串"),
]
for src, exp_v, exp_k, note in PARSE_CASES:
    v, k = core.parse_cell(src)
    ok = (v == exp_v) and (k == exp_k)
    if not ok:
        fails += 1
        print(f"[FAIL] parse_cell({src!r}) -> {(v, k)!r}  期望 {(exp_v, exp_k)!r}  | {note}")
    else:
        print(f"[ ok ] parse_cell({src!r}) -> {(v, k)!r}  | {note}")

# is_date
print("\n-- is_date --")
for src in ["20240123", "2024-01-23", "2024/1/23", "2024.01.23",
            "2024年1月23日", "99999999", "2.903.00"]:
    print(f"  {src!r} -> {core.is_date(src)}")

total = len(CASES) + len(PARSE_CASES)
print(f"\n合计 {total} 例，失败 {fails} 例")
sys.exit(1 if fails else 0)
