# -*- coding: utf-8 -*-
"""fix_number / parse_cell 单元测试"""
import sys
sys.stdout.reconfigure(encoding="utf-8")
import core

CASES = [
    # (输入, 期望值, 说明)
    ("2.903.00", 2903.0, "千分位点被认成小数点"),
    ("2,903.00", 2903.0, "标准千分位"),
    ("3,015.64", 3015.64, "标准千分位"),
    ("4. 69", 4.69, "小数点后误插空格"),
    ("2 . 9 0 3 . 0 0", 2903.0, "数字间多处空格"),
    ("4, 69", 4.69, "逗号后误插空格"),
    ("20240123", 20240123, "8 位日期保持 int"),
    ("1.00", 1.0, "普通两位小数"),
    ("48,175.58", 48175.58, "大额标准写法"),
    ("2.925.67", 2925.67, "千分位点被认成小数点"),
    ("\u00a5123.45", 123.45, "带货币符号"),
    ("1,234,567.89", 1234567.89, "多级千分位"),
    ("2,903", 2903, "纯千分位整数"),
    ("3.14159", 3.14159, "多位小数"),
    ("4.6", 4.6, "一位小数"),
    ("12.345", 12.345, "模糊情形：保持原样不猜测"),
    ("1.234", 1.234, "模糊情形：保持原样不猜测"),
    ("2.903", 2.903, "模糊情形：保持原样不猜测"),
    ("123.456", 123456, "整数部分符合分组规律 -> 修正"),
    ("100", 100, "纯整数"),
    # 以下应保持字符串
    ("", "", "空串"),
    ("-", "-", "单符号"),
    ("abc", "abc", "非数字"),
    ("2024年1月", "2024年1月", "中文混杂不猜测"),
]

fails = 0
for src, exp, note in CASES:
    got, raw = core.fix_number(src)
    ok = (got == exp) and (type(got) is type(exp))
    if not ok:
        fails += 1
        print(f"[FAIL] {src!r} -> {got!r} ({type(got).__name__})  期望 {exp!r}  | {note}")
    else:
        print(f"[ ok ] {src!r} -> {got!r}  | {note}")

# parse_cell
print("\n-- parse_cell --")
for src in ["20240123", "2024-01-23", "2.903.00", "代理付款", "", "4. 69"]:
    print(f"  {src!r} -> {core.parse_cell(src)}")

# is_date
print("\n-- is_date --")
for src in ["20240123", "2024-01-23", "2024/1/23", "2024年1月23日", "99999999", "2.903.00"]:
    print(f"  {src!r} -> {core.is_date(src)}")

print(f"\n合计 {len(CASES)} 例，失败 {fails} 例")
sys.exit(1 if fails else 0)
